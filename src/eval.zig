// Mobility: bonus per reachable square, centred on a typical count.
const mob_mg = [6]i32{ 0, 4, 5, 2, 1, 0 };
const mob_eg = [6]i32{ 0, 4, 5, 4, 2, 0 };
const mob_center = [6]i32{ 0, 4, 6, 6, 12, 0 };

/// Static evaluation in centipawns from the side to move's point of view.
pub fn evaluate(pos: *const Position) i32 {
    var mg = [2]i32{ 0, 0 };
    var eg = [2]i32{ 0, 0 };
    var phase: i32 = 0;
    const occ = pos.occupied();

    for (0..2) |ci| {
        const c: bb.Color = @intCast(ci);
        const flip: u6 = if (c == bb.WHITE) 56 else 0;
        const not_own = ~pos.colors[c];
        for (0..6) |pti| {
            const pt: bb.PieceType = @intCast(pti);
            var pcs = pos.piecesOf(c, pt);
            while (pcs != 0) {
                const sq = bb.popLsb(&pcs);
                const idx = sq ^ flip;
                mg[ci] += mg_value[pti] + mg_pst[pti][idx];
                eg[ci] += eg_value[pti] + eg_pst[pti][idx];
                phase += phase_inc[pti];
                if (pt != bb.PAWN and pt != bb.KING) {
                    const a: u64 = switch (pt) {
                        bb.KNIGHT => atk.knight[sq],
                        bb.BISHOP => atk.bishop(sq, occ),
                        bb.ROOK => atk.rook(sq, occ),
                        else => atk.queen(sq, occ),
                    };
                    const n: i32 = @intCast(bb.popcount(a & not_own));
                    mg[ci] += (n - mob_center[pti]) * mob_mg[pti];
                    eg[ci] += (n - mob_center[pti]) * mob_eg[pti];
                }
            }
        }
        if (bb.popcount(pos.piecesOf(c, bb.BISHOP)) >= 2) {
            mg[ci] += 30;
            eg[ci] += 50;
        }
    }

    const us = pos.side;
    const them = us ^ 1;
    const p = @min(phase, 24);
    const mg_score = mg[us] - mg[them];
    const eg_score = eg[us] - eg[them];
    return @divTrunc(mg_score * p + eg_score * (24 - p), 24) + 10; // +10 tempo
}
